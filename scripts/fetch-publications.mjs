#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(
  __dirname,
  "..",
  "src",
  "data",
  "publications.generated.ts",
);

const AUTHOR_ID = process.env.OPENALEX_AUTHOR_ID || "A5051561323";
const MAILTO = process.env.OPENALEX_MAILTO || "diegomorra.dm@gmail.com";
const API = `https://api.openalex.org/works?filter=author.id:${AUTHOR_ID}&per-page=100&sort=publication_date:desc&mailto=${encodeURIComponent(MAILTO)}`;

async function main() {
  console.log(`[publications] fetching from OpenAlex (author ${AUTHOR_ID})...`);
  let data;
  try {
    const res = await fetch(API);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    data = await res.json();
  } catch (e) {
    console.warn(
      `[publications] WARN: fetch failed (${e.message}). Keeping existing file if present.`,
    );
    if (!fs.existsSync(OUT)) {
      writeFile([]);
    }
    return;
  }

  const pubs = (data.results || []).map((w) => ({
    title: w.title || "",
    year: w.publication_year || 0,
    venue: w.primary_location?.source?.display_name || w.type || "",
    doi: w.doi || null,
    citedBy: w.cited_by_count || 0,
    openAccessUrl: w.open_access?.oa_url || null,
    type: w.type || null,
  }));

  writeFile(pubs);
  console.log(`[publications] wrote ${pubs.length} publications.`);
}

function writeFile(pubs) {
  const header = [
    "// AUTO-GENERATED by scripts/fetch-publications.mjs",
    "// Source: OpenAlex API (https://openalex.org)",
    "// To refresh: npm run fetch-publications",
    'import type { Publication } from "./publications";',
    "",
  ].join("\n");
  const body =
    `export const publications: Publication[] = ${JSON.stringify(pubs, null, 2)};\n\n` +
    `export const publicationsFetchedAt = ${JSON.stringify(new Date().toISOString())};\n`;
  fs.writeFileSync(OUT, header + body);
}

main();
